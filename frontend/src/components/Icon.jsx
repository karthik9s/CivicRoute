// Short fee label for compact places (lists, chips). Returns null, 'FREE' marker check via isFree().
export const isFree = (fees = []) => !!fees[0] && /free|मुफ़्त|ఉచిత/i.test(fees[0].amount)
export function shortFee(fees = [], lang = 'en') {
  const f = fees[0]
  if (!f) return null
  if (isFree(fees)) return t(lang, 'free')
  const m = f.amount.match(/₹\s?[\d,.]+/)
  return m ? `${m[0]}${fees.length > 1 ? '+' : ''}` : t(lang, 'fee_on_page')
}
